"""Generate procedural IES light profiles for RulesHorror (plain Python 3, no dependencies).

Run:  python create_ies_profiles.py
Output: IES/T_IES_Downlight.ies (import into Unreal as a TextureLightProfile).

The profile is rotationally symmetric (one horizontal angle) and only lights downward.
It replaces the purchased BrutalistLevelKit T_IES1 used by the L_Lobby spotlight:
a bright narrow beam, a soft spill, and a bright wide arc just below the horizon.
"""

import math
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent / "IES"
TARGET_LUMENS = 850.0
STEP_DEG = 2.5


def downlight_shape(theta_deg):
    """Relative intensity for a vertical angle (0 = straight down, 90 = horizontal)."""
    if theta_deg >= 90.0:
        return 0.0
    beam = math.exp(-0.5 * (theta_deg / 10.0) ** 2)
    spill = 0.12 * math.cos(math.radians(theta_deg))
    wings = 0.38 * math.exp(-0.5 * ((theta_deg - 74.0) / 6.5) ** 2)  # bright wide arc near the ceiling
    fade = 1.0 - max(0.0, (theta_deg - 84.0) / 6.0)  # soft cut-off at the horizon
    return (beam + spill + wings) * fade


def lumens_for(candelas, angles_deg):
    """Integrate a symmetric candela distribution over the sphere (trapezoid rule)."""
    total = 0.0
    for i in range(len(angles_deg) - 1):
        a0, a1 = math.radians(angles_deg[i]), math.radians(angles_deg[i + 1])
        c0, c1 = candelas[i], candelas[i + 1]
        total += 0.5 * (c0 * math.sin(a0) + c1 * math.sin(a1)) * (a1 - a0)
    return 2.0 * math.pi * total


def write_ies(path, name, shape):
    count = int(round(180.0 / STEP_DEG)) + 1
    angles = [i * STEP_DEG for i in range(count)]
    rel = [shape(a) for a in angles]
    scale = TARGET_LUMENS / lumens_for(rel, angles)
    cd = [r * scale for r in rel]

    lines = [
        "IESNA:LM-63-2002",
        "[TEST] Procedural profile generated by create_ies_profiles.py",
        "[MANUFAC] RulesHorror",
        f"[LUMINAIRE] {name}",
        "TILT=NONE",
        f"1 -1 1 {count} 1 1 2 0 0 0",
        "1 1 0",
    ]

    def chunk(values, fmt):
        row = []
        for v in values:
            row.append(fmt.format(v))
            if len(row) == 10:
                lines.append(" ".join(row))
                row = []
        if row:
            lines.append(" ".join(row))

    chunk(angles, "{:.1f}")
    lines.append("0.0")
    chunk(cd, "{:.2f}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Wrote {path} (peak {max(cd):.1f} cd, {lumens_for(cd, angles):.0f} lm)")


if __name__ == "__main__":
    write_ies(OUT_DIR / "T_IES_Downlight.ies", "Soft downlight", downlight_shape)
